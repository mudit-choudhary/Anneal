"""Retrieval quality: the original pipeline vs the current one, measured.

    python scripts/retrieval_eval.py build      # build every arm's index
    python scripts/retrieval_eval.py questions  # generate + verify the question set
    python scripts/retrieval_eval.py run        # retrieve and score
    python scripts/retrieval_eval.py report     # print the last run again
    python scripts/retrieval_eval.py all        # the three steps in order

Three arms, so the two changes can be separated instead of confounded:

    original   PyMuPDF page dump   recursive 512/103 chars   all-MiniLM-L6-v2
    rechunked  PyMuPDF page dump   recursive 512/103 chars   bge-base-en-v1.5
    current    YOLO layout parse   structure-aware chunks    bge-base-en-v1.5

  original vs rechunked  → what the embedding-model change alone bought
  rechunked vs current   → what layout parsing + structure chunking bought
  original vs current    → the whole change

`original` and `rechunked` are reconstructed from commit c41e756: a plain
`page.get_text()` per page prefixed with "Page: N", split by
RecursiveCharacterTextSplitter(512, overlap 103).

Everything is written under data/eval/ and indexed into a throwaway vector
store at data/eval/vector_db — the real corpus is never touched.

Ground truth
------------
Questions are generated by the local model from the *raw PDF text*, never
from either pipeline's chunks, so neither arm is favoured by construction.
Each question carries a verbatim answer span, and a question is kept only if
that span survives in every arm's text. Questions whose span is missing from
some arm are reported separately as a coverage figure — that is a real
finding about the pipeline, but scoring on them would measure text
availability rather than retrieval.
"""

