os.environ.setdefault("VECTOR_DB_PATH", str(EVAL_VECTOR_DB))

RAW_PDF_DIR = PDF_DIR
PROCESSED_DIR = LIVE_PROCESSED_DIR

# --- the three arms ---------------------------------------------------------
ARMS = {
    "original": {
        "label": "original (page dump + 512-char chunks + MiniLM)",
        "text": "baseline",
        "chunker": "recursive",
        "model": "sentence-transformers/all-MiniLM-L6-v2",
        "collection": "eval_original",
    },
    "rechunked": {
        "label": "same text and chunks, bge-base embeddings",
        "text": "baseline",
        "chunker": "recursive",
        "model": "BAAI/bge-base-en-v1.5",
        "collection": "eval_rechunked",
    },
    "current": {
        "label": "current (YOLO layout + structure-aware chunks + bge-base)",
        "text": "layout",
        "chunker": "structure",
        "model": "BAAI/bge-base-en-v1.5",
        "collection": "eval_current",
    },
}

BASELINE_CHUNK_SIZE = 512
BASELINE_OVERLAP = int(BASELINE_CHUNK_SIZE * 0.2) + 1   # 103, as in c41e756
KS = (1, 3, 5, 10)
# Recall@k is not comparable between arms whose chunks differ in size: the
# baseline's 512-char chunks with 103 chars of overlap give the same passage
# two or three chances to land in a top-k list, while the current arm's
# 1500-char chunks give it one. Scoring at an equal *character* budget removes
# that artifact and matches what actually reaches the answering model.
BUDGETS = (2000, 4000, 8000)


# --------------------------------------------------------------- text arms
def baseline_text(pdf_path):
    """Reproduce the original parser: whole-page text, no layout awareness."""
    import fitz

    doc = fitz.open(pdf_path)
    out = ""
    for n in range(len(doc)):
        text = doc[n].get_text().strip()
        if text and text[-1] == ".":
            text += "\n"
        out += f"\n\nPage: {n + 1}\n" + text
    doc.close()
    return out


def build_baseline_text(limit=None):
    BASELINE_TEXT_DIR.mkdir(parents=True, exist_ok=True)
    pdfs = sorted(RAW_PDF_DIR.glob("*.pdf"))[:limit]
    for i, pdf in enumerate(pdfs, 1):
        target = BASELINE_TEXT_DIR / f"{pdf.stem}.txt"
        if not target.exists():
            target.write_text(baseline_text(pdf), encoding="utf-8")
        print(f"  [{i}/{len(pdfs)}] {pdf.stem[:60]}", flush=True)
    return pdfs


# --------------------------------------------------------------- chunk arms
def recursive_chunks(text):
    from langchain_text_splitters import RecursiveCharacterTextSplitter

    splitter = RecursiveCharacterTextSplitter(
        chunk_size=BASELINE_CHUNK_SIZE, chunk_overlap=BASELINE_OVERLAP,
        separators=["\n\n", "\n", " ", ""])
    return splitter.split_text(text)


def structure_chunks(processed_json):
    from grain_growth import chunk_file

    chunks, _skipped = chunk_file(processed_json)
    return [c["text"] for c in chunks]


def chunks_for(arm, stem):
    """(texts, ok) for one paper under one arm."""
    cfg = ARMS[arm]
    if cfg["text"] == "baseline":
        path = BASELINE_TEXT_DIR / f"{stem}.txt"
        if not path.exists():
            return [], False
        return recursive_chunks(path.read_text(encoding="utf-8")), True
    path = PROCESSED_DIR / f"{stem}.json"
    if not path.exists():
        return [], False
    return structure_chunks(path), True


# --------------------------------------------------------------- indexing
def _embedder(model_name, device):
    from chromadb.utils import embedding_functions

    if "bge" in model_name:
        from embeddings import BGEEmbeddingFunction  # adds bge's query instruction
        return BGEEmbeddingFunction(model_name=model_name, device=device,
                                    normalize_embeddings=True)
    return embedding_functions.SentenceTransformerEmbeddingFunction(
        model_name=model_name, device=device)


def build_arm(arm, stems, device, rebuild=False):
    import chromadb

    cfg = ARMS[arm]
    client = chromadb.PersistentClient(path=str(EVAL_VECTOR_DB))
    if rebuild:
        try:
            client.delete_collection(cfg["collection"])
        except Exception:                                    # noqa: BLE001
            pass
    fn = _embedder(cfg["model"], device)
    col = client.get_or_create_collection(
        name=cfg["collection"], embedding_function=fn,
        metadata={"hnsw:space": "cosine"})
    if col.count() and not rebuild:
        print(f"  {arm}: {col.count()} chunks already indexed (--rebuild to redo)")
        return col.count()

    total = 0
    started = time.time()
    for i, stem in enumerate(stems, 1):
        texts, ok = chunks_for(arm, stem)
        if not ok or not texts:
            print(f"  {arm}: [{i}/{len(stems)}] no text for {stem[:50]}", flush=True)
            continue
        col.add(documents=texts,
                metadatas=[{"filename": stem, "chunk_id": j} for j in range(len(texts))],
                ids=[f"{stem}__{j}" for j in range(len(texts))])
        total += len(texts)
        print(f"  {arm}: [{i}/{len(stems)}] +{len(texts)} chunks "
              f"({total} total)", flush=True)
    print(f"  {arm}: {total} chunks in {time.time() - started:.0f}s")
    return total


# --------------------------------------------------------------- questions
QUESTION_PROMPT = """You are building an evaluation set for a search system over research papers.

Below is text from one paper. Write {n} questions that this text answers.

Rules:
- Each question must be answerable from this text alone.
- Each question must be specific enough that it identifies THIS paper, not any
  paper on the topic. Name the method, dataset or metric involved.
- Do not write questions about the figures or the page layout.
- "answer" must be copied VERBATIM from the text: a span of 4 to 20 words that
  appears in it character for character. Do not paraphrase or reformat it.

Reply with JSON only, no other text:
{{"questions": [{{"question": "...", "answer": "..."}}]}}

Text:
{text}
"""


def _normalise(s):
    return re.sub(r"\s+", " ", s or "").strip().lower()


def ask_model(prompt, cfg, timeout=300):
    import requests

    local = cfg["llm"]["local"]
    r = requests.post(f"{local['url'].rstrip('/')}/api/chat", json={
        "model": local["model"],
        "messages": [{"role": "user", "content": prompt}],
        "stream": False, "think": False,
        "options": {"num_ctx": int(local.get("num_ctx", 6144)), "temperature": 0.3},
    }, timeout=timeout)
    r.raise_for_status()
    return r.json()["message"]["content"]


def parse_questions(reply):
    match = re.search(r"\{.*\}", reply, re.S)
    if not match:
        return []
    try:
        return json.loads(match.group(0)).get("questions", [])
    except json.JSONDecodeError:
        return []


def generate_questions(stems, per_paper, chars, cfg):
    """Questions come from the raw PDF text, so neither arm is favoured."""
    from common.settings import load                                # noqa: F401

    out = []
    for i, stem in enumerate(stems, 1):
        source = BASELINE_TEXT_DIR / f"{stem}.txt"
        if not source.exists():
            continue
        # Skip the first page: title/abstract questions are too easy and every
        # arm gets them right, which compresses the difference being measured.
        text = source.read_text(encoding="utf-8")[1500:1500 + chars]
        try:
            reply = ask_model(QUESTION_PROMPT.format(n=per_paper, text=text), cfg)
        except Exception as e:                                      # noqa: BLE001
            print(f"  [{i}/{len(stems)}] {stem[:45]}: model error {e}")
            continue
        got = parse_questions(reply)
        for q in got:
            if q.get("question") and q.get("answer"):
                out.append({"paper": stem, "question": q["question"].strip(),
                            "answer": q["answer"].strip()})
        print(f"  [{i}/{len(stems)}] {stem[:45]}: {len(got)} candidates", flush=True)
    return out


def verify_questions(candidates, stems):
    """Keep only questions whose answer span survives in every arm's text.

    A span that one arm lost is a coverage finding, not a retrieval one, so it
    is counted and set aside rather than scored.
    """
    texts = defaultdict(dict)
    for arm in ARMS:
        for stem in stems:
            chunks, ok = chunks_for(arm, stem)
            texts[arm][stem] = _normalise(" ".join(chunks)) if ok else ""

    kept, dropped = [], []
    for q in candidates:
        answer = _normalise(q["answer"])
        if len(answer) < 15:
            dropped.append({**q, "why": "answer span too short to be distinctive"})
            continue
        missing = [a for a in ARMS if answer not in texts[a].get(q["paper"], "")]
        if missing:
            dropped.append({**q, "why": f"answer text absent from: {', '.join(missing)}"})
            continue
        kept.append(q)
    return kept, dropped


# --------------------------------------------------------------- scoring
def retrieve(arm, question, k, device):
    import chromadb

    cfg = ARMS[arm]
    client = chromadb.PersistentClient(path=str(EVAL_VECTOR_DB))
    fn = _embedder(cfg["model"], device)
    col = client.get_collection(cfg["collection"], embedding_function=fn)
    res = col.query(query_texts=[question], n_results=k,
                    include=["documents", "metadatas"])
    return list(zip(res["metadatas"][0], res["documents"][0]))


def score_arm(arm, questions, device):
    import chromadb

    cfg = ARMS[arm]
    client = chromadb.PersistentClient(path=str(EVAL_VECTOR_DB))
    fn = _embedder(cfg["model"], device)
    col = client.get_collection(cfg["collection"], embedding_function=fn)

    maxk = max(KS)
    res = col.query(query_texts=[q["question"] for q in questions], n_results=maxk,
                    include=["documents", "metadatas"])

    paper_hits = {k: 0 for k in KS}
    answer_hits = {k: 0 for k in KS}
    budget_hits = {b: 0 for b in BUDGETS}
    reciprocal = 0.0
    per_question = []

    for i, q in enumerate(questions):
        metas, docs = res["metadatas"][i], res["documents"][i]
        papers = [m["filename"] for m in metas]
        answer = _normalise(q["answer"])

        rank = next((j + 1 for j, p in enumerate(papers) if p == q["paper"]), None)
        reciprocal += 1.0 / rank if rank else 0.0

        first_answer = None
        for j in range(maxk):
            if answer in _normalise(docs[j]):
                first_answer = j + 1
                break

        for k in KS:
            if rank and rank <= k:
                paper_hits[k] += 1
            if first_answer and first_answer <= k:
                answer_hits[k] += 1

        # equal-characters comparison: fill each budget in rank order and see
        # whether the answer arrived before the budget ran out
        for b in BUDGETS:
            used, found = 0, False
            for doc in docs:
                if used >= b:
                    break
                used += len(doc)
                if answer in _normalise(doc):
                    found = True
                    break
            if found:
                budget_hits[b] += 1

        per_question.append({"question": q["question"], "paper": q["paper"],
                             "paper_rank": rank, "answer_rank": first_answer})

    n = len(questions)
    return {
        "arm": arm, "label": cfg["label"], "n_questions": n,
        "chunks": col.count(),
        "paper_recall": {str(k): paper_hits[k] / n for k in KS},
        "answer_recall": {str(k): answer_hits[k] / n for k in KS},
        "answer_recall_by_chars": {str(b): budget_hits[b] / n for b in BUDGETS},
        "median_chunk_chars": sorted(len(d) for row in res["documents"] for d in row)[
            sum(len(row) for row in res["documents"]) // 2],
        "mrr": reciprocal / n,
        "per_question": per_question,
    }


# --------------------------------------------------------------- llm judge
JUDGE_PROMPT = """You are grading a search system.

QUESTION: {question}

EXCERPTS RETRIEVED:
{context}

Can the QUESTION be answered from these excerpts alone? Answer "yes" only if
the excerpts actually state the information the question asks for. Topical
relevance is not enough.

Reply with JSON only: {{"answerable": true or false}}
"""


def judge_context(arm, questions, device, budget, cfg):
    """Does the retrieved context actually contain what the question asks for?

    The verbatim-span metric punishes correct retrieval whenever a fact appears
    in more than one place — retrieving the Results section scores zero if the
    generator happened to copy its span from the Abstract. Asking the model
    whether the context suffices measures the thing the pipeline exists to do.
    """
    import chromadb

    acfg = ARMS[arm]
    client = chromadb.PersistentClient(path=str(EVAL_VECTOR_DB))
    fn = _embedder(acfg["model"], device)
    col = client.get_collection(acfg["collection"], embedding_function=fn)
    res = col.query(query_texts=[q["question"] for q in questions],
                    n_results=max(KS), include=["documents"])

    ok = 0
    for i, q in enumerate(questions):
        used, parts = 0, []
        for doc in res["documents"][i]:
            if used >= budget:
                break
            parts.append(doc)
            used += len(doc)
        context = "\n\n---\n\n".join(parts)
        try:
            reply = ask_model(JUDGE_PROMPT.format(question=q["question"], context=context), cfg)
            match = re.search(r"\{.*\}", reply, re.S)
            answerable = bool(json.loads(match.group(0)).get("answerable")) if match else False
        except Exception:                                        # noqa: BLE001
            answerable = False
        ok += answerable
        print(f"    {arm} [{i + 1}/{len(questions)}] {'yes' if answerable else 'no '}", flush=True)
    return ok / len(questions)


# --------------------------------------------------------------- chunk shape
_MID_SENTENCE = re.compile(r"^[a-z,;)\]]")
_PAGE_NOISE = re.compile(r"(^|\n)\s*Page:\s*\d+\s*(\n|$)")


def chunk_shape(arm, stems):
    """Intrinsic quality — no questions needed, no ground truth to argue with."""
    lengths, mid, noisy, total = [], 0, 0, 0
    for stem in stems:
        texts, ok = chunks_for(arm, stem)
        if not ok:
            continue
        for t in texts:
            total += 1
            lengths.append(len(t))
            body = t.strip()
            # the heading prefix the current arm adds is not the chunk's prose
            if "\n\n" in body:
                body = body.split("\n\n", 1)[1].strip()
            if _MID_SENTENCE.match(body):
                mid += 1
            if _PAGE_NOISE.search(t):
                noisy += 1
    lengths.sort()
    return {
        "chunks": total,
        "median_chars": lengths[len(lengths) // 2] if lengths else 0,
        "starts_mid_sentence": mid / total if total else 0.0,
        "contains_page_marker": noisy / total if total else 0.0,
    }


# --------------------------------------------------------------- reporting
def pct(x):
    return f"{100 * x:5.1f}%"


def print_report(results):
    arms = results["arms"]
    print("\n" + "=" * 78)
    print(f"RETRIEVAL EVAL — {results['n_questions']} verified questions "
          f"over {results['n_papers']} papers")
    print("=" * 78)

    for a in arms:
        print(f"\n  {a['arm']:<10} {a['label']}")
        print(f"  {'':<10} {a['chunks']} chunks indexed")

    def table(title, key):
        print(f"\n{title}")
        print(f"  {'arm':<11}" + "".join(f"{'@' + str(k):>9}" for k in KS) + f"{'MRR':>9}")
        for a in arms:
            row = "".join(pct(a[key][str(k)]) + "    " for k in KS)
            print(f"  {a['arm']:<11}" + row + f"{a['mrr']:8.3f}")

    table("Right paper retrieved (paper recall@k)", "paper_recall")
    table("Answer text present in the top-k chunks — NOT comparable across arms", "answer_recall")

    print("\nAnswer text found within an equal character budget (the fair comparison)")
    print(f"  {'arm':<11}" + "".join(f"{str(b) + 'ch':>11}" for b in BUDGETS) + f"{'median chunk':>14}")
    for a in arms:
        row = "".join(pct(a["answer_recall_by_chars"][str(b)]) + "      " for b in BUDGETS)
        print(f"  {a['arm']:<11}" + row + f"{a.get('median_chunk_chars', 0):>10}")

    if any("context_sufficient" in a for a in arms):
        print("\nContext sufficient to answer, judged by the model (equal budget)")
        for a in arms:
            if "context_sufficient" in a:
                print(f"  {a['arm']:<11}{pct(a['context_sufficient'])}")

    print("\nChunk shape")
    print(f"  {'arm':<11}{'chunks':>8}{'median':>9}{'mid-sentence':>14}{'page marker':>13}")
    for a in arms:
        s = results["shape"][a["arm"]]
        print(f"  {a['arm']:<11}{s['chunks']:>8}{s['median_chars']:>9}"
              f"{pct(s['starts_mid_sentence']):>14}{pct(s['contains_page_marker']):>13}")

    base = {a["arm"]: a for a in arms}
    n = results["n_questions"]
    if {"original", "rechunked", "current"} <= set(base):
        print("\nWhat each change bought (answer found within 4000 characters)")
        o = base["original"]["answer_recall_by_chars"]["4000"]
        r = base["rechunked"]["answer_recall_by_chars"]["4000"]
        c = base["current"]["answer_recall_by_chars"]["4000"]
        print(f"  embedding model   {pct(o)} → {pct(r)}   {100 * (r - o):+5.1f} points")
        print(f"  parse + chunking  {pct(r)} → {pct(c)}   {100 * (c - r):+5.1f} points")
        print(f"  combined          {pct(o)} → {pct(c)}   {100 * (c - o):+5.1f} points")

    # A proportion measured on n questions carries about this much noise; saying
    # so stops a run of 24 questions being read as a verdict.
    margin = 100 * 1.96 * (0.25 / max(n, 1)) ** 0.5
    print(f"\n  With {n} questions the 95% margin of error on any single "
          f"percentage is about ±{margin:.0f} points.")
    if margin > 10:
        print("  Differences smaller than that are noise. Re-run with more papers "
              "(--limit) and\n  more questions per paper (--per-paper) before "
              "drawing a conclusion.")

    cov = results.get("coverage", {})
    if cov.get("dropped"):
        print(f"\nCoverage: {cov['dropped']} of {cov['candidates']} candidate questions "
              f"were set aside because the answer text was missing from some arm.")
        for arm, n in sorted(cov.get("missing_by_arm", {}).items()):
            print(f"  missing from {arm:<11} {n}")
        print("  These are not scored: they measure what each pipeline keeps, not what")
        print("  retrieval finds. See data/eval/questions.json for the full list.")
    print()


# --------------------------------------------------------------- commands
def corpus_stems(limit=None):
    stems = sorted(p.stem for p in PROCESSED_DIR.glob("*.json"))
    return stems[:limit] if limit else stems


def cmd_build(args):
    EVAL_DIR.mkdir(parents=True, exist_ok=True)
    print("Reconstructing the original parser's text (PyMuPDF page dump)")
    build_baseline_text(args.limit)
    stems = corpus_stems(args.limit)
    print(f"\nIndexing {len(stems)} papers into {EVAL_VECTOR_DB}")
    for arm in ARMS:
        build_arm(arm, stems, args.device, rebuild=args.rebuild)


def cmd_questions(args):
    from common.settings import load

    EVAL_DIR.mkdir(parents=True, exist_ok=True)
    stems = corpus_stems(args.limit)
    print(f"Generating up to {args.per_paper} questions from each of {len(stems)} papers")
    candidates = generate_questions(stems, args.per_paper, args.chars, load())
    print(f"\n{len(candidates)} candidates; verifying answer spans survive in every arm")
    kept, dropped = verify_questions(candidates, stems)

    missing_by_arm = defaultdict(int)
    for d in dropped:
        for arm in ARMS:
            if arm in d.get("why", ""):
                missing_by_arm[arm] += 1

    QUESTIONS_FILE.write_text(json.dumps({
        "questions": kept, "dropped": dropped,
        "missing_by_arm": dict(missing_by_arm),
    }, indent=2), encoding="utf-8")
    print(f"kept {len(kept)}, set aside {len(dropped)} → {QUESTIONS_FILE}")


def cmd_run(args):
    if not QUESTIONS_FILE.exists():
        sys.exit("No question set yet — run `retrieval_eval.py questions` first.")
    data = json.loads(QUESTIONS_FILE.read_text(encoding="utf-8"))
    questions = data["questions"][:args.limit_questions] if args.limit_questions else data["questions"]
    if not questions:
        sys.exit("The question set is empty; regenerate it.")

    stems = sorted({q["paper"] for q in questions})
    arms = []
    for arm in ARMS:
        print(f"scoring {arm} …", flush=True)
        arms.append(score_arm(arm, questions, args.device))

    if args.judge:
        from common.settings import load
        cfg = load()
        print("\nasking the model whether each arm's context is sufficient …")
        for a in arms:
            a["context_sufficient"] = judge_context(a["arm"], questions, args.device,
                                                    args.judge_budget, cfg)

    results = {
        "generated_at": time.strftime("%Y-%m-%d %H:%M:%S"),
        "n_questions": len(questions), "n_papers": len(stems),
        "arms": arms,
        "shape": {arm: chunk_shape(arm, stems) for arm in ARMS},
        "coverage": {
            "candidates": len(questions) + len(data.get("dropped", [])),
            "dropped": len(data.get("dropped", [])),
            "missing_by_arm": data.get("missing_by_arm", {}),
        },
    }
    RESULTS_FILE.write_text(json.dumps(results, indent=2), encoding="utf-8")
    print_report(results)
    print(f"Full results: {RESULTS_FILE}")


def cmd_report(args):
    if not RESULTS_FILE.exists():
        sys.exit("No results yet — run `retrieval_eval.py run` first.")
    print_report(json.loads(RESULTS_FILE.read_text(encoding="utf-8")))


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--device", default=os.environ.get("EMBED_DEVICE", "cpu"),
                    help="cpu (default; leaves VRAM for the answering model) or cuda")
    sub = ap.add_subparsers(dest="cmd", required=True)

    b = sub.add_parser("build", help="reconstruct baseline text and index all three arms")
    b.add_argument("--limit", type=int, help="only the first N papers")
    b.add_argument("--rebuild", action="store_true", help="discard existing indexes")
    b.set_defaults(func=cmd_build)

    q = sub.add_parser("questions", help="generate and verify the question set")
    q.add_argument("--limit", type=int, help="only the first N papers")
    q.add_argument("--per-paper", type=int, default=3)
    q.add_argument("--chars", type=int, default=6000, help="characters of paper text per prompt")
    q.set_defaults(func=cmd_questions)

    r = sub.add_parser("run", help="retrieve for every arm and score")
    r.add_argument("--limit-questions", type=int)
    r.add_argument("--judge", action="store_true",
                   help="also ask the local model whether each arm's context can "
                        "answer the question (slow, but the metric that matters)")
    r.add_argument("--judge-budget", type=int, default=4000,
                   help="characters of retrieved context given to the judge")
    r.set_defaults(func=cmd_run)

    p = sub.add_parser("report", help="reprint the last results")
    p.set_defaults(func=cmd_report)

    a = sub.add_parser("all", help="build, questions, run")
    a.add_argument("--limit", type=int)
    a.add_argument("--per-paper", type=int, default=3)
    a.add_argument("--chars", type=int, default=6000)
    a.add_argument("--rebuild", action="store_true")
    a.add_argument("--limit-questions", type=int)
    a.add_argument("--judge", action="store_true")
    a.add_argument("--judge-budget", type=int, default=4000)
    a.set_defaults(func=lambda args: (cmd_build(args), cmd_questions(args), cmd_run(args)))

    args = ap.parse_args()
    args.func(args)


