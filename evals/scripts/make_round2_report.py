    add("")
    not_a_metric = ("_eligible", "answer_words", "context_chars", "chunk")
    flat = {k: v for k, v in spread.items()
            if v is not None and v < 0.05 and not any(x in k for x in not_a_metric)}
    add("Metrics whose spread across the nine cells is under 5 points cannot separate the systems, "
        "whatever their pedigree: " + ", ".join(f"`{k}` ({100 * v:.1f} pts)"
                                                for k, v in sorted(flat.items(), key=lambda x: x[1])[:8]) + ".")
    add("")

    sv = None
    if False:
        add("### Does chunk shape predict the outcome?")
        add("")
        add("| Shape metric | Outcome | Spearman |")
        add("|---|---|---|")
        for k, v in sv.items():
            if k == "n_cells":
                continue
            sm, out_m = k.split(" vs ")
            add(f"| {sm} | {out_m} | {v:+.2f} |")
        add("")
        add("![chunk shape against retrieval](assets/fig_r2_shape.svg)")
        add("")
        add(f"Over {sv.get('n_cells', 9)} cells, with shape and outcome measured on the same papers. "
            "The chunker sets both the shape and the retrieval behaviour, so this is a relationship "
            "between two consequences of the same choice, not evidence that fixing the shape causes "
            "the gain.")
        add("")

    jv = None
    if False:
        add("### Do the answer scores measure anything?")
        add("")
        add("| Check | Result |")
        add("|---|---|")
        for name, label in (("gemma_correctness_vs_numeric_reference", "Judge vs the objective number check"),
                            ("nli_fact_recall_vs_numeric_reference", "Fact recall vs the objective number check")):
            d = jv.get(name)
            if d:
                add(f"| {label} | **{pct(d['agreement'])}** agreement (n={num(d['n'])}); "
                    f"{d['mean_when_number_right']:.2f} when the number is right, "
                    f"{d['mean_when_number_wrong']:.2f} when wrong |")
