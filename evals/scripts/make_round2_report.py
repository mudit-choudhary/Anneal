"""Generate the combined round 1 + round 2 report.

    python evals/scripts/make_round2_report.py            # draft, keeps Report.md
    python evals/scripts/make_round2_report.py --final    # writes Report.md

Round 1 and round 2 share file names in places, so every round-1 input is named
explicitly here: round 2 overwrote evals/questions/dataset.json (400 questions,
was 100) and evals/corpus/manifest.json (514 papers, was 103). Reading the wrong
one would silently mix the rounds.

Numbers come from the files; verdicts come from round2_analysis.json, which
applies the rules fixed in round2_preregistration.json before the run.
"""

