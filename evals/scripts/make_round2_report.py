def pct(v, nd=1):
    return "—" if v is None else f"{100 * v:.{nd}f}%"


def num(v, nd=0):
    return "—" if v is None else f"{v:,.{nd}f}"


def f3(v):
    return "—" if not isinstance(v, (int, float)) else f"{v:.3f}"


def pv(p):
    return "—" if p is None else ("<0.001" if p < 0.001 else f"{p:.3f}")


def parse_stats():
    """Round-2 parse cost: current totals minus the round-1 backup."""
    out = {}
    for p in PARSERS:
        now = json.loads((REPO / "evals" / "parsed" / p / "_stats.json").read_text())
        old_f = REPO / "evals" / "parsed" / p / "_stats_round1.json"
        old = json.loads(old_f.read_text()) if old_f.exists() else {"pages": 0, "seconds": 0.0}
        pages = now["pages"] - old.get("pages", 0)
        secs = now["seconds"] - old.get("seconds", 0.0)
        out[p] = {"pages": pages, "seconds": secs,
                  "sec_per_page": secs / pages if pages else None,
                  "vram_rise_mb": now.get("vram_rise_mb"),
                  "failures": len(now.get("failures", []))}
    return out


